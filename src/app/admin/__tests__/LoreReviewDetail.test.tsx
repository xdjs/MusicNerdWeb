import {render,screen,fireEvent,waitFor,act} from '@testing-library/react';
import LoreReviewDetail from '../LoreReviewDetail';
import {approveUgcAdminAction} from '@/app/actions/serverActions';
import {updateSourceStatus} from '@/app/actions/dashboardActions';
import type {ReviewItem} from '@/lib/contributions/adminReviewTypes';
jest.mock('next/navigation',()=>({useRouter:()=>({refresh:jest.fn()})}));
jest.mock('@/app/actions/serverActions',()=>({approveUgcAdminAction:jest.fn()}));
jest.mock('@/app/actions/dashboardActions',()=>({updateSourceStatus:jest.fn()}));
const base:ReviewItem={id:'report-id',type:'links',artistId:'artist-id',artistName:'Artist',title:'Submission',url:'https://example.test',createdAt:null,origin:'user',actorName:'Contributor',actorId:'user',activityId:null,trigger:null,bioSnapshot:null,details:null,reason:null};
const onClose=jest.fn();
const onReviewed=jest.fn();
const request=jest.fn();
beforeEach(()=>{jest.clearAllMocks();global.fetch=request;});
it.each(['Mark resolved','Dismiss'])('reviews a correction with %s only through its PATCH endpoint',async label=>{
 request.mockResolvedValue({ok:true});
 render(<LoreReviewDetail item={{...base,type:'corrections',bioSnapshot:'Original bio',details:'Correction detail'}} onClose={onClose} onReviewed={onReviewed}/>);
 fireEvent.click(screen.getByRole('button',{name:label}));
 await waitFor(()=>expect(onReviewed).toHaveBeenCalledTimes(1));
 expect(request).toHaveBeenCalledWith('/api/admin/bio-corrections/report-id',{method:'PATCH',headers:{'Content-Type':'application/json'},body:JSON.stringify({status:label==='Dismiss'?'dismissed':'resolved'})});
 expect(approveUgcAdminAction).not.toHaveBeenCalled();
 expect(updateSourceStatus).not.toHaveBeenCalled();
});
it.each([['Approve','approved'],['Reject','rejected']])('reviews source %s with expected pending status',async(label,status)=>{
 jest.mocked(updateSourceStatus).mockResolvedValue({success:true});
 render(<LoreReviewDetail item={{...base,type:'sources'}} onClose={onClose} onReviewed={onReviewed}/>);
 fireEvent.click(screen.getByRole('button',{name:label}));
 await waitFor(()=>expect(onReviewed).toHaveBeenCalledTimes(1));
 expect(updateSourceStatus).toHaveBeenCalledWith('report-id',status,'pending');
 expect(approveUgcAdminAction).not.toHaveBeenCalled();
 expect(request).not.toHaveBeenCalled();
});
it('approves the selected link only and ignores duplicate clicks while pending',async()=>{
 let finish!:(result:{status:string;message:string})=>void;
 jest.mocked(approveUgcAdminAction).mockImplementation(()=>new Promise(resolve=>{finish=resolve;}));
 render(<LoreReviewDetail item={base} onClose={onClose} onReviewed={onReviewed}/>);
 const approve=screen.getByRole('button',{name:'Approve'});
 fireEvent.click(approve);fireEvent.click(approve);
 expect(approveUgcAdminAction).toHaveBeenCalledTimes(1);
 expect(approveUgcAdminAction).toHaveBeenCalledWith(['report-id']);
 expect(approve).toBeDisabled();
 expect(screen.queryByRole('button',{name:'Reject'})).not.toBeInTheDocument();
 await act(async()=>finish({status:'success',message:'Approved'}));
 expect(onReviewed).toHaveBeenCalledTimes(1);
 expect(updateSourceStatus).not.toHaveBeenCalled();
});
it('keeps a failed source review open and allows retry',async()=>{
 jest.mocked(updateSourceStatus).mockResolvedValue({success:false,error:'Source changed'});
 render(<LoreReviewDetail item={{...base,type:'sources'}} onClose={onClose} onReviewed={onReviewed}/>);
 fireEvent.click(screen.getByRole('button',{name:'Approve'}));
 expect(await screen.findByRole('alert')).toHaveTextContent('Source changed');
 expect(screen.getByRole('dialog')).toBeVisible();
 expect(screen.getByRole('button',{name:'Approve'})).toBeEnabled();
 expect(onClose).not.toHaveBeenCalled();expect(onReviewed).not.toHaveBeenCalled();
});
it('keeps a failed correction report open without routing to another review action',async()=>{
 request.mockResolvedValue({ok:false});
 render(<LoreReviewDetail item={{...base,type:'corrections'}} onClose={onClose} onReviewed={onReviewed}/>);
 fireEvent.click(screen.getByRole('button',{name:'Mark resolved'}));
 expect(await screen.findByRole('alert')).toHaveTextContent('Could not review this report');
 expect(screen.getByRole('dialog')).toBeVisible();
 expect(onReviewed).not.toHaveBeenCalled();expect(onClose).not.toHaveBeenCalled();
 expect(approveUgcAdminAction).not.toHaveBeenCalled();expect(updateSourceStatus).not.toHaveBeenCalled();
});
